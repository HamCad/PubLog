    public sealed class Unit
    {
        public string Name, Dim, Canon; public double Factor, Offset;
        // Rounded to 12 significant digits so exact conversions (25.4 mm = 1 in)
        // compare equal instead of differing in the last bit.
        public double ToCanon(double v) { return RoundSig(v * Factor + Offset); }
        public static double RoundSig(double v)
        {
            if (v == 0 || double.IsNaN(v) || double.IsInfinity(v)) return v;
            double scale = Math.Pow(10, 11 - Math.Floor(Math.Log10(Math.Abs(v))));
            return Math.Round(v * scale) / scale;
        }
    }

