.SYNOPSIS
  Alternate-part finder over PUB LOG characteristics: reply parser, derived
  index (publog_alt.db), in-memory drill-down engine and a localhost web UI.

.DESCRIPTION
  V_CHARACTERISTICS holds one clear-text reply per NIIN per MRC (requirement),
  generated by FLIS from coded replies, so it is very regular:
      INCHES  NOMINAL  0.500
      INCHES  MINIMUM  0.657 AND INCHES  MAXIMUM  0.781
      FIRST END  INCHES  0.500
      CELSIUS  -55.0 TO 125.0
      OVERALL  STEEL COMP 1010 OR STEEL COMP 1015
  A double space separates fields (location qualifier, unit, NOMINAL/MINIMUM/
  MAXIMUM, value). AltParts.ReplyParser turns each reply into atoms:
      numeric: qualifier, kind (NOM/MIN/MAX/RNG/VAL), lo/hi in a canonical unit
      text:    qualifier, one atom per OR-alternative
  Unknown units are never guessed: the field stays in the qualifier and the
  value is only compared with replies that use the same wording.

  Build-AltPartIndex writes publog_alt.db next to publog.db (derived, safe to
  delete and rebuild):
      ac_value      one row per atom, clustered by pool (WITHOUT ROWID)
      ac_item       NIIN -> pool, INC, FSC, item name
      ac_pool       pool = INC, except INC 77777 ("non-approved item name"),
                    which is split by item name
      ac_pool_char  per pool/MRC/qualifier profile and quality statistics
      ac_build_log  what was built from which publog.db cut

  Start-AltPartFinder.ps1 serves altparts.html and a JSON API on 127.0.0.1.
  Everything is PowerShell 5.1 + C# 5 compiled by Add-Type + winsqlite3.dll.
#>

