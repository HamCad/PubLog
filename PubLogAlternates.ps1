    public sealed class Atom
    {
        public string Qual = "";   // location / condition words, may be ""
        public string Kind;        // NOM MIN MAX RNG VAL TXT
        public string Text;        // TXT: the value atom; numeric: the unit wording ("" = implied by the MRC)
        public double Lo = double.NaN, Hi = double.NaN;  // canonical unit (numeric only)
        public string Dim = "";    // dimension for numeric ("" = unit implied by the MRC)
        public bool IsNumeric { get { return Kind != "TXT"; } }
        public override string ToString()
        {
            if (!IsNumeric) return (Qual.Length > 0 ? "[" + Qual + "] " : "") + Text;
            return (Qual.Length > 0 ? "[" + Qual + "] " : "") + Kind + " " + Lo.ToString("R", CultureInfo.InvariantCulture) + ".." + Hi.ToString("R", CultureInfo.InvariantCulture) + " " + Dim + "(" + Text + ")";
        }
    }

    public static class ReplyParser
    {
        static readonly string[] DS = new[] { "  " };
        static readonly Regex Num = new Regex(@"^[-+]?(?:\d+(?:\.\d*)?|\.\d+)$", RegexOptions.Compiled);
        static readonly Regex Frac = new Regex(@"^(?:(\d+)[- ])?(\d+)/(\d+)$", RegexOptions.Compiled);
        static readonly Regex NumRange = new Regex(@"^(\S+) TO (\S+)$", RegexOptions.Compiled);
        static readonly Regex NumList = new Regex(@"^\S+(?: (?:AND|OR) \S+)+$", RegexOptions.Compiled);
        static readonly Regex Joiner = new Regex(@" (AND|OR) ", RegexOptions.Compiled);

        public static bool TryNumber(string s, out double v)
        {
            v = double.NaN;
            if (Num.IsMatch(s)) return double.TryParse(s, NumberStyles.Float, CultureInfo.InvariantCulture, out v);
            Match m = Frac.Match(s);
            if (m.Success)
            {
                double whole = m.Groups[1].Success ? double.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture) : 0;
                double den = double.Parse(m.Groups[3].Value, CultureInfo.InvariantCulture);
                if (den == 0) return false;
                v = whole + double.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture) / den;
                return true;
            }
            return false;
        }

        static bool HasDigit(string s) { foreach (char c in s) if (c >= '0' && c <= '9') return true; return false; }

        // Splits a reply into groups at " AND " / " OR " only where the next
        // piece starts a new field group (contains a double space) or where the
        // previous group was numeric-terminated; "NYLON AND RESIN" stays whole.
        static List<string> Groups(string r, List<string> joiners)
        {
            var groups = new List<string>();
            int start = 0;
            foreach (Match m in Joiner.Matches(r))
            {
                string next = r.Substring(m.Index + m.Length);
                int nextEnd = NextJoin(next);
                string nextPiece = nextEnd < 0 ? next : next.Substring(0, nextEnd);
                string prevPiece = r.Substring(start, m.Index - start);
                bool split = nextPiece.Contains("  ") || (prevPiece.Contains("  ") && EndsNumeric(prevPiece) && StartsLikeGroup(nextPiece));
                if (split)
                {
                    groups.Add(prevPiece);
                    joiners.Add(m.Groups[1].Value);
                    start = m.Index + m.Length;
                }
            }
            groups.Add(r.Substring(start));
            return groups;
        }
        static int NextJoin(string s) { Match m = Joiner.Match(s); return m.Success ? m.Index : -1; }
        static bool EndsNumeric(string piece)
        {
            string[] f = piece.Split(DS, StringSplitOptions.RemoveEmptyEntries);
            double v; return f.Length > 0 && TryNumber(f[f.Length - 1].Trim(), out v);
        }
        static bool StartsLikeGroup(string piece) { double v; return !TryNumber(piece.Trim(), out v); }

        public static List<Atom> Parse(string reply)
        {
            var atoms = new List<Atom>();
            if (reply == null) return atoms;
            string r = reply.Trim();
            if (r.Length == 0) return atoms;
            var joiners = new List<string>();
            List<string> groups = Groups(r, joiners);
            var numeric = new List<List<Atom>>();
            bool allNumeric = true;
            string inheritQual = "";
            foreach (string g in groups)
            {
                List<Atom> na = ParseNumericGroup(g, ref inheritQual);
                if (na == null) { allNumeric = false; break; }
                numeric.Add(na);
            }
            if (allNumeric)
            {
                foreach (var list in numeric) atoms.AddRange(list);
                PairMinMax(atoms, joiners, numeric);
                return atoms;
            }
            foreach (string g in groups)
            {
                string[] f = g.Split(DS, StringSplitOptions.RemoveEmptyEntries);
                string value = f[f.Length - 1].Trim();
                string qual = f.Length > 1 ? string.Join(" ", f.Take(f.Length - 1).Select(x => x.Trim())) : "";
                foreach (string alt in Regex.Split(value, " OR "))
                {
                    string t = alt.Trim();
                    if (t.Length == 0) continue;
                    atoms.Add(new Atom { Qual = qual, Kind = "TXT", Text = t });
                }
            }
            return atoms;
        }

        // A numeric group: optional word fields, then a number, "a TO b" or
        // "a AND b ..." as the last field. Returns null if it is not numeric.
        static List<Atom> ParseNumericGroup(string g, ref string inheritQual)
        {
            string[] f = g.Split(DS, StringSplitOptions.RemoveEmptyEntries);
            for (int i = 0; i < f.Length; i++) f[i] = f[i].Trim();
            if (f.Length == 0) return null;
            string last = f[f.Length - 1];
            var values = new List<double[]>();   // {lo, hi}
            double a, b;
            if (TryNumber(last, out a)) values.Add(new[] { a, a });
            else
            {
                Match m = NumRange.Match(last);
                if (m.Success && TryNumber(m.Groups[1].Value, out a) && TryNumber(m.Groups[2].Value, out b)) values.Add(new[] { Math.Min(a, b), Math.Max(a, b) });
                else if (NumList.IsMatch(last))
                {
                    foreach (string p in Regex.Split(last, " (?:AND|OR) ")) { if (!TryNumber(p, out a)) return null; values.Add(new[] { a, a }); }
                }
                else return null;
            }
            string kind = null; Unit unit = null; string unitWord = "";
            var qual = new List<string>();
            for (int i = 0; i < f.Length - 1; i++)
            {
                string w = f[i];
                // A field that is itself a number is not a qualifier ("26.0" mid-reply);
                // words with digits ("5TH RADIO INTERFERENCE", "AT 200 PCT") are.
                double dummy;
                if (TryNumber(w, out dummy) || NumRange.IsMatch(w)) return null;
                if (w == "NOMINAL" || w == "MINIMUM" || w == "MAXIMUM") { if (kind != null) return null; kind = w.Substring(0, 3); continue; }
                Unit u = Units.Find(w);
                if (u != null && unit == null) { unit = u; unitWord = w; continue; }
                qual.Add(w);
            }
            string q = string.Join(" ", qual);
            if (q.Length == 0) q = inheritQual; else inheritQual = q;
            var list = new List<Atom>();
            bool range = NumRange.IsMatch(last) && !TryNumber(last, out a);
            foreach (double[] v in values)
            {
                var at = new Atom { Qual = q, Text = unitWord, Dim = unit == null ? "" : unit.Dim };
                at.Kind = range ? "RNG" : (kind ?? "VAL");
                at.Lo = unit == null ? v[0] : unit.ToCanon(v[0]);
                at.Hi = unit == null ? v[1] : unit.ToCanon(v[1]);
                if (at.Lo > at.Hi) { double t = at.Lo; at.Lo = at.Hi; at.Hi = t; }
                list.Add(at);
            }
            return list;
        }

        // "UNIT  MINIMUM  a AND UNIT  MAXIMUM  b" -> one RNG atom.
        static void PairMinMax(List<Atom> atoms, List<string> joiners, List<List<Atom>> byGroup)
        {
            for (int i = 0; i < atoms.Count; i++)
            {
                Atom x = atoms[i];
                if (x.Kind != "MIN") continue;
                for (int j = i + 1; j < atoms.Count; j++)
                {
                    Atom y = atoms[j];
                    if (y.Kind == "MAX" && y.Qual == x.Qual && y.Dim == x.Dim && y.Text == x.Text)
                    {
                        x.Kind = "RNG"; x.Hi = Math.Max(x.Lo, y.Hi); x.Lo = Math.Min(x.Lo, y.Hi);
                        atoms.RemoveAt(j);
                        break;
                    }
                }
            }
        }

        // Text normalisation used for equality: upper case, single spaces,
        // no trailing punctuation.
        public static string NormText(string s)
        {
            if (s == null) return "";
            var sb = new StringBuilder(s.Length);
            bool sp = false;
            foreach (char c0 in s.Trim().ToUpperInvariant())
            {
                char c = c0;
                if (char.IsWhiteSpace(c)) { if (!sp && sb.Length > 0) { sb.Append(' '); sp = true; } continue; }
                sp = false; sb.Append(c);
            }
            string t = sb.ToString().TrimEnd(' ', ',', ';', '.', ':');
            return t;
        }

        // True when a text reply still looks like a number with a unit we could
        // not read -- reported as a parse gap, never guessed.
        public static bool LooksNumeric(string value)
        {
            string[] f = value.Split(DS, StringSplitOptions.RemoveEmptyEntries);
            double v;
            return f.Length >= 2 && TryNumber(f[f.Length - 1].Trim(), out v);
        }
    }

