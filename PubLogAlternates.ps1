    // Engine: answers the web UI's JSON API from publog_alt.db + publog.db.
    // A pool's atoms are loaded into memory once (LRU) and every drill-down
    // step is evaluated there.
    // ------------------------------------------------------------------
    public sealed class PoolData
    {
        public long Pool;
        public long[] Niins;            // distinct, sorted
        public int[] Start, End;        // atom range per NIIN
        public int[] Key;               // atom -> char key index
        public byte[] Kind;             // 0 TXT, 1 NOM, 2 MIN, 3 MAX, 4 RNG, 5 VAL
        public int[] Txt;               // atom -> string index (TXT) or unit word index (numeric), -1 none
        public double[] Lo, Hi;
        public List<string> Strings = new List<string>();
        public Dictionary<string, int> StringIx = new Dictionary<string, int>();
        public List<string> KeyMrc = new List<string>(), KeyQual = new List<string>();
        public Dictionary<string, int> KeyIx = new Dictionary<string, int>();
        public Dictionary<long, int> NiinIx = new Dictionary<long, int>();
        // Text keys whose values are nearly unique per item (descriptions, end
        // items): useful to read, useless as evidence of interchangeability.
        public bool[] Descriptive;
        public static readonly string[] KindNames = { "TXT", "NOM", "MIN", "MAX", "RNG", "VAL" };
        public int Str(string s)
        {
            if (s == null) return -1;
            int i; if (StringIx.TryGetValue(s, out i)) return i;
            i = Strings.Count; Strings.Add(s); StringIx[s] = i; return i;
        }
        public int KeyOf(string mrc, string qual)
        {
            string k = mrc + "\u0001" + qual; int i;
            if (KeyIx.TryGetValue(k, out i)) return i;
            i = KeyMrc.Count; KeyMrc.Add(mrc); KeyQual.Add(qual); KeyIx[k] = i; return i;
        }
        public int FindKey(string mrc, string qual) { int i; return KeyIx.TryGetValue(mrc + "\u0001" + (qual ?? ""), out i) ? i : -1; }
        public int Atoms { get { return Key.Length; } }
    }

