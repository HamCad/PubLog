                    }
                    else
                    {
                        a.Num++;
                        string dim = s.Text(8) ?? ""; string unit = s.Text(5) ?? "";
                        int c; a.Dims.TryGetValue(dim, out c); a.Dims[dim] = c + 1;
                        a.UnitWords.TryGetValue(unit, out c); a.UnitWords[unit] = c + 1;
                        double lo = s.Double(6), hi = s.Double(7);
                        a.Vals.Add((lo + hi) / 2); a.ValNiin.Add(niin);
                    }
                    if (++n % 5000000 == 0 && log != null) log(string.Format("  profiled {0:N0} atoms", n));
