        static Dictionary<string, object> Histogram(List<double> vals, string unit)
        {
            vals.Sort();
            double min = vals[0], max = vals[vals.Count - 1];
            bool log = min > 0 && max / min > 100;
            int bins = 24; var counts = new int[bins];
            double a = log ? Math.Log10(min) : min, b = log ? Math.Log10(max) : max;
            if (b - a < 1e-12) { b = a + 1; }
            foreach (double v in vals)
            {
                double x = log ? Math.Log10(v) : v;
                int i = (int)((x - a) / (b - a) * bins); if (i >= bins) i = bins - 1; if (i < 0) i = 0;
                counts[i]++;
            }
            var edges = new List<object>();
            for (int i = 0; i <= bins; i++) { double e = a + (b - a) * i / bins; double c = log ? Math.Pow(10, e) : e; edges.Add(Num(unit == null ? c : Units.FromCanon(unit, c))); }
            Func<double, object> disp = v => Num(unit == null ? v : Units.FromCanon(unit, v));
            return new Dictionary<string, object> { { "n", vals.Count }, { "log", log }, { "counts", counts }, { "edges", edges }, { "unit", unit },
                { "min", disp(min) }, { "max", disp(max) }, { "median", disp(vals[vals.Count / 2]) } };
        }

