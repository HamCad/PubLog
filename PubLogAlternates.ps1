        // ---- resolve: NIIN/NSN, part number, or item name -------------------
        object Resolve(string q)
        {
            q = (q ?? "").Trim();
            var res = new Dictionary<string, object> { { "query", q } };
            if (q.Length == 0) throw new ArgumentException("Type a NIIN, NSN, part number or item name.");
            string digits = new string(q.Where(char.IsDigit).ToArray());
            string stripped = new string(q.Where(c => c != '-' && c != ' ').ToArray());
            if ((digits.Length == 9 || digits.Length == 13) && digits.Length == stripped.Length)
            {
                long niin = ParseNiin(digits);
                res["kind"] = "niin";
                res["items"] = ItemsFor(new[] { niin }, null);
                return res;
            }
            // CAGE + part number as "CAGE:PN" or "PN CAGE" (CAGE = 5 alphanumerics)
            string cage = null, pn = q;
            int colon = q.IndexOf(':');
            if (colon == 5) { cage = q.Substring(0, 5).ToUpperInvariant(); pn = q.Substring(6); }
            string norm = NormPart(pn);
            var parts = new List<Dictionary<string, object>>();
            if (norm.Length >= 2)
            {
                string sql = "SELECT p.niin, p.part_number, p.cage_code, p.rncc, p.rnvc FROM pl.pl_part_norm p WHERE p.pn_norm = ?" + (cage != null ? " AND p.cage_code = ?" : "") + " LIMIT 300";
                parts = cage != null ? Db.Rows(sql, norm, cage) : Db.Rows(sql, norm);
                res["partMatch"] = "exact";
                if (parts.Count == 0 && norm.Length >= 4)
                {
                    // Prefix match on the normalised part number (uses the index).
                    parts = Db.Rows("SELECT p.niin, p.part_number, p.cage_code, p.rncc, p.rnvc FROM pl.pl_part_norm p WHERE p.pn_norm >= ? AND p.pn_norm < ? LIMIT 100", norm, norm + "￿");
                    res["partMatch"] = "prefix";
                }
            }
            if (parts.Count > 0)
            {
                res["kind"] = "part";
                var niins = parts.Select(p => long.Parse((string)p["niin"])).Distinct().ToArray();
                var byNiin = parts.GroupBy(p => (string)p["niin"]).ToDictionary(g => g.Key, g => g.Select(p => (object)new Dictionary<string, object> {
                    { "part_number", p["part_number"] }, { "cage", p["cage_code"] }, { "rncc", p["rncc"] }, { "rnvc", p["rnvc"] } }).ToList());
                res["items"] = ItemsFor(niins, byNiin);
                // "o-ring" is both a part-number prefix and an item name: offer both.
                if (q.Any(char.IsLetter) && colon != 5) res["pools"] = FindPools(q);
                return res;
            }
            res["kind"] = "name";
            res["pools"] = FindPools(q);
            return res;
        }

        List<object> ItemsFor(IEnumerable<long> niins, Dictionary<string, List<object>> partsByNiin)
        {
            var list = new List<object>();
            foreach (long n in niins.Take(200))
            {
                string ns = NiinText(n);
                var r = Db.Rows("SELECT n.fsc, n.item_name, n.inc, a.pool, a.replies, p.name AS pool_name, p.niins AS pool_niins FROM pl.pl_p_flis_nsn n LEFT JOIN ac_item a ON a.niin = ? LEFT JOIN ac_pool p ON p.pool = a.pool WHERE n.niin = ? LIMIT 1", n, ns);
                var d = new Dictionary<string, object> { { "niin", ns } };
                if (r.Count > 0) { foreach (var kv in r[0]) d[kv.Key] = kv.Value; d["nsn"] = (r[0]["fsc"] ?? "") + ns; }
                else d["missing"] = true;
                List<object> parts;
                if (partsByNiin != null && partsByNiin.TryGetValue(ns, out parts)) d["matched_parts"] = parts;
                list.Add(d);
            }
            return list;
        }

        // ---- item names ------------------------------------------------------------
        // FLIS item names read noun first, then modifiers, separated by commas:
        // NUT,SELF-LOCKING,HEXAGON. A few are written with ", ".
        public static string[] NameSegments(string name)
        {
            return (name ?? "").Split(',').Select(x => x.Trim()).Where(x => x.Length > 0).ToArray();
        }
        public static string NormName(string name) { return string.Join(",", NameSegments((name ?? "").ToUpperInvariant())); }
        public static bool InNameFamily(string name, string fam)
        {
            string n = NormName(name), f = NormName(fam);
            return f.Length > 0 && (n == f || n.StartsWith(f + ",", StringComparison.Ordinal));
        }

        sealed class NameRow { public long Pool, Inc, Niins; public string Name, Norm, Root, Fscs; public bool Odd; }
        List<NameRow> names;
        // All item names (~330 K, most of them one-item INC 77777 pools), kept in
        // memory so the name tree and family lookups need no table scans.
        List<NameRow> Names()
        {
            if (names != null) return names;
            var list = new List<NameRow>();
            using (var st = Db.Prepare("SELECT pool, inc, name, niins, fscs FROM ac_pool"))
                while (st.Step())
                {
                    var r = new NameRow { Pool = st.Long(0), Inc = st.Long(1), Name = st.Text(2) ?? "", Niins = st.Long(3), Fscs = st.Text(4) };
                    r.Norm = NormName(r.Name); int c = r.Norm.IndexOf(','); r.Root = c < 0 ? r.Norm : r.Norm.Substring(0, c); r.Odd = r.Inc == Builder.NonApprovedInc; list.Add(r);
                }
            names = list;
            return names;
        }
        static Dictionary<string, object> NameDict(NameRow r)
        {
            return new Dictionary<string, object> { { "pool", r.Pool }, { "inc", r.Inc }, { "name", r.Name }, { "niins", r.Niins }, { "fscs", r.Fscs } };
        }
        static string RootOf(string normName) { int c = normName.IndexOf(','); return c < 0 ? normName : normName.Substring(0, c); }
        static bool InFam(NameRow r, string normFam) { return r.Root == RootOf(normFam) && (r.Norm == normFam || r.Norm.StartsWith(normFam + ",", StringComparison.Ordinal)); }

        // Item names matching the text, plus every approved name sharing their
        // leading noun, so the page can nest them (NUT > PLAIN > HEXAGON) with
        // whole-family counts. INC 77777 names are mostly one-item pools: only
        // the largest matches are listed, and the rest are counted per noun.
        object FindPools(string q)
        {
            string u = (q ?? "").Trim().ToUpperInvariant();
            var all = Names();
            var hits = all.Where(r => r.Name.IndexOf(u, StringComparison.Ordinal) >= 0).ToList();
            var roots = hits.Where(r => !r.Odd).GroupBy(r => r.Root).OrderByDescending(g => g.Sum(r => r.Niins)).Select(g => g.Key).Take(60).ToList();
            var rootSet = new HashSet<string>(roots);
            var hitSet = new HashSet<long>(hits.Select(r => r.Pool));
            var rows = new List<object>();
            foreach (var r in all.Where(r => !r.Odd && rootSet.Contains(r.Root)).OrderByDescending(r => r.Niins).Take(1500))
            { var d = NameDict(r); d["match"] = hitSet.Contains(r.Pool); rows.Add(d); }
            foreach (var r in hits.Where(r => r.Odd).OrderByDescending(r => r.Niins).Take(25))
            { var d = NameDict(r); d["match"] = true; rows.Add(d); }
            var oddByRoot = all.Where(r => r.Odd && rootSet.Contains(r.Root)).GroupBy(r => r.Root)
                .Select(g => (object)new Dictionary<string, object> { { "root", g.Key }, { "pools", g.Count() }, { "niins", g.Sum(r => r.Niins) } }).ToList();
            // Colloquial names (H6) point at an INC.
            var coll = Db.Rows(@"SELECT DISTINCT c.colloquial_name, p.pool, p.name, p.niins FROM pl.pl_v_colloquial_name c JOIN ac_pool p ON p.inc = CAST(c.inc AS INTEGER)
                                 WHERE c.colloquial_name LIKE ? ORDER BY p.niins DESC LIMIT 20", "%" + u + "%");
            return new Dictionary<string, object> { { "pools", rows }, { "colloquial", coll }, { "nonApprovedByRoot", oddByRoot } };
        }

        const int MaxFamilyPools = 2000;
        // Every item name in a family (NUT,PLAIN -> NUT,PLAIN,HEXAGON, NUT,PLAIN,ROUND, ...).
        // INC 77777 names only when asked for, largest first, at most MaxFamilyPools.
        object NameFamily(string fam, bool nonApproved)
        {
            string f = NormName(fam);
            if (f.Length == 0) throw new ArgumentException("name is required.");
            var appr = Names().Where(r => !r.Odd && InFam(r, f)).OrderBy(r => r.Norm).ToList();
            var odd = Names().Where(r => r.Odd && InFam(r, f)).OrderByDescending(r => r.Niins).ToList();
            var list = appr.Select(NameDict).ToList();
            if (nonApproved) list.AddRange(odd.Take(MaxFamilyPools).Select(NameDict));
            return new Dictionary<string, object> { { "name", f },
                { "approved", new Dictionary<string, object> { { "pools", appr.Count }, { "niins", appr.Sum(r => r.Niins) } } },
                { "nonApproved", new Dictionary<string, object> { { "pools", odd.Count }, { "niins", odd.Sum(r => r.Niins) } } },
                { "truncated", nonApproved && odd.Count > MaxFamilyPools }, { "pools", list } };
        }

        // The wider families an item name belongs to, narrowest first, with sizes:
        // NUT,SELF-LOCKING,HEXAGON -> NUT,SELF-LOCKING (24 names) -> NUT (86 names).
        object NameAncestors(string name)
        {
            var seg = NameSegments((name ?? "").ToUpperInvariant());
            var list = new List<object>();
            for (int n = seg.Length - 1; n >= 1; n--)
            {
                string fam = string.Join(",", seg.Take(n));
                var appr = Names().Where(r => !r.Odd && InFam(r, fam)).ToList();
                var odd = Names().Where(r => r.Odd && InFam(r, fam)).ToList();
                list.Add(new Dictionary<string, object> { { "name", fam }, { "pools", appr.Count }, { "niins", appr.Sum(r => r.Niins) },
                    { "nonApprovedPools", odd.Count }, { "nonApprovedNiins", odd.Sum(r => r.Niins) } });
            }
            return new Dictionary<string, object> { { "name", NormName(name) }, { "ancestors", list } };
        }

        // ---- item detail -------------------------------------------------------
        object Item(long niin)
        {
            string ns = NiinText(niin);
            var d = new Dictionary<string, object> { { "niin", ns } };
            var id = Db.Rows("SELECT * FROM pl.pl_vw_nsn WHERE niin = ? LIMIT 1", ns);
            if (id.Count == 0) throw new KeyNotFoundException("NIIN " + ns + " is not in PUB LOG (P_FLIS_NSN).");
            var ident = id[0];
            d["identification"] = ident;
            d["decoded"] = new Dictionary<string, object> {
                { "demil", Coded("DMIL", ident["demil"]) }, { "crit_cd", Coded("CRIT_CD", ident["crit_cd"]) }, { "hmic", Coded("HMIC", ident["hmic"]) },
                { "esd_emi", Coded("ESD_EMI", ident["esd_emi"]) }, { "pmic", Coded("PMIC", ident["pmic"]) }, { "niin_asgmt", Coded("NIIN_ASGMT", ident["niin_asgmt"]) } };
            var mgmt = Db.Rows("SELECT moe, aac, sos, ui, unit_price, qup, slc, ciic, effective_date FROM pl.pl_v_flis_management WHERE niin = ?", ns);
            foreach (var m in mgmt) { m["aac_text"] = Help("AAC", m["aac"] as string); m["moe_text"] = Help("MOE", m["moe"] as string); }
            d["management"] = mgmt;
            var parts = Db.Rows("SELECT part_number, cage_code, company_name, rncc, rnvc, cage_status, msds FROM pl.pl_vw_part WHERE niin = ?", ns);
            foreach (var p in parts) { p["rncc_text"] = Help("RNCC", p["rncc"] as string); p["rnvc_text"] = Help("RNVC", p["rnvc"] as string); p["cage_status_text"] = Help("CAGE_STATUS", p["cage_status"] as string); }
            d["parts"] = parts;
            d["relations"] = Relations(ns, parts);
            var chars = Db.Rows("SELECT mrc, requirements_statement AS statement, clear_text_reply AS reply FROM pl.pl_v_characteristics WHERE niin = ?", ns);
            long pool = PoolOf(niin);
            d["pool"] = pool == long.MinValue ? null : (object)pool;
            if (pool != long.MinValue)
            {
                var pr = Db.Rows("SELECT * FROM ac_pool WHERE pool = ?", pool);
                d["poolInfo"] = pr.Count > 0 ? pr[0] : null;
                PoolData pd = LoadPool(pool);
                int ix; if (pd.NiinIx.TryGetValue(niin, out ix)) d["atoms"] = AtomsOf(pd, ix);
            }
            d["characteristics"] = chars;
            return d;
        }

        List<object> AtomsOf(PoolData p, int ix)
        {
            var list = new List<object>();
            for (int a = p.Start[ix]; a < p.End[ix]; a++) list.Add(AtomJson(p, a));
            return list;
        }
        Dictionary<string, object> AtomJson(PoolData p, int a)
        {
            int k = p.Key[a];
            var d = new Dictionary<string, object> { { "mrc", p.KeyMrc[k] }, { "qual", p.KeyQual[k] }, { "kind", PoolData.KindNames[p.Kind[a]] } };
            string s = p.Txt[a] >= 0 ? p.Strings[p.Txt[a]] : null;
            if (p.Kind[a] == 0) d["txt"] = s;
            else
            {
                d["lo"] = Num(p.Lo[a]); d["hi"] = Num(p.Hi[a]); d["unit"] = s;
                if (s != null) { d["loDisplay"] = Num(Units.FromCanon(s, p.Lo[a])); d["hiDisplay"] = Num(Units.FromCanon(s, p.Hi[a])); }
            }
            return d;
        }

        // Known relationships from FLIS itself: standardization decisions,
        // cancelled/replacement NIINs, management-history replacements,
        // phrases, and the same part number on other NIINs.
        object Relations(string ns, List<Dictionary<string, object>> parts)
        {
            var rel = new List<object>();
            long n = long.Parse(ns, IC);
            // Precomputed at build time in both directions (ac_rel), so these are index lookups.
            foreach (var r in Db.Rows("SELECT other, type, code, code_field, text FROM ac_rel WHERE niin = ?", n))
                rel.Add(Rel((string)r["type"], r["other"] == null ? null : NiinText(Convert.ToInt64(r["other"])), r["text"] as string, r["code"] as string, r["code_field"] as string, null));
            // Same normalised part number on other NIINs (reference numbers are
            // shared by specs/standards and by true duplicates).
            var seen = new HashSet<string>();
            foreach (var p in parts)
            {
                string norm = NormPart(p["part_number"] as string);
                if (norm.Length < 3 || !seen.Add(norm)) continue;
                foreach (var r in Db.Rows("SELECT niin, part_number, cage_code, rncc, rnvc FROM pl.pl_part_norm WHERE pn_norm = ? AND niin <> ? LIMIT 50", norm, ns))
                    rel.Add(Rel("same_part_number", r["niin"] as string, "Shares reference number " + p["part_number"] + (Equals(r["cage_code"], p["cage_code"]) ? " (same CAGE)" : " (CAGE " + r["cage_code"] + ")"), r["rncc"] as string, "RNCC", null));
            }
            foreach (Dictionary<string, object> o in rel)
            {
                string t = o["niin"] as string;
                if (t == null) continue;
                var nm = Db.Rows("SELECT fsc, item_name FROM pl.pl_p_flis_nsn WHERE niin = ? LIMIT 1", t);
                if (nm.Count > 0) { o["item_name"] = nm[0]["item_name"]; o["nsn"] = (nm[0]["fsc"] ?? "") + t; }
            }
            return rel;
        }
        static readonly Regex NsnRx = new Regex(@"\b(\d{4})-?(\d{2})-?(\d{3})-?(\d{4})\b", RegexOptions.Compiled);
        public static string NsnInText(string s)
        {
            if (string.IsNullOrEmpty(s)) return null;
            Match m = NsnRx.Match(s);
            return m.Success ? m.Groups[2].Value + m.Groups[3].Value + m.Groups[4].Value : null;
        }
        static string Tail9(string s)
        {
            if (s == null) return null;
            string d = new string(s.Where(char.IsDigit).ToArray());
            return d.Length >= 9 ? d.Substring(d.Length - 9) : null;
        }
