        Dictionary<string, object> Coded(string field, object code)
        {
            string c = code == null ? null : code.ToString();
            if (string.IsNullOrEmpty(c)) return null;
            return new Dictionary<string, object> { { "code", c }, { "text", Help(field, c) } };
        }

        public PoolData LoadPool(long pool)
        {
            LinkedListNode<PoolData> hit;
            if (cacheIx.TryGetValue(pool, out hit)) { cache.Remove(hit); cache.AddFirst(hit); return hit.Value; }
            var p = new PoolData { Pool = pool };
            var niins = new List<long>(); var start = new List<int>(); var end = new List<int>();
            var key = new List<int>(); var kind = new List<byte>(); var txt = new List<int>(); var lo = new List<double>(); var hi = new List<double>();
            long last = -1;
            using (var s = Db.Prepare("SELECT niin, mrc, qual, kind, txt, lo, hi FROM ac_value WHERE pool = ? ORDER BY niin, seq"))
            {
                s.Bind(pool);
                while (s.Step())
                {
                    long niin = s.Long(0);
                    if (niin != last)
                    {
                        if (last >= 0) end.Add(key.Count);
                        niins.Add(niin); start.Add(key.Count); last = niin;
                    }
                    key.Add(p.KeyOf(s.Text(1), s.Text(2) ?? ""));
                    string k = s.Text(3);
                    byte kb = (byte)Array.IndexOf(PoolData.KindNames, k);
                    kind.Add(kb);
                    txt.Add(p.Str(s.Text(4)));
                    lo.Add(s.IsNull(5) ? double.NaN : s.Double(5));
                    hi.Add(s.IsNull(6) ? double.NaN : s.Double(6));
                }
            }
            if (last >= 0) end.Add(key.Count);
            p.Niins = niins.ToArray(); p.Start = start.ToArray(); p.End = end.ToArray();
            p.Key = key.ToArray(); p.Kind = kind.ToArray(); p.Txt = txt.ToArray(); p.Lo = lo.ToArray(); p.Hi = hi.ToArray();
            for (int i = 0; i < p.Niins.Length; i++) p.NiinIx[p.Niins[i]] = i;
            int nk = p.KeyMrc.Count;
            var keyNiins = new int[nk]; var keyLast = Enumerable.Repeat(-1, nk).ToArray(); var keyTxt = new HashSet<int>[nk];
            for (int i = 0; i < p.Niins.Length; i++)
                for (int a = p.Start[i]; a < p.End[i]; a++)
                {
                    int k = p.Key[a];
                    if (keyLast[k] != i) { keyLast[k] = i; keyNiins[k]++; }
                    if (p.Kind[a] == 0) { if (keyTxt[k] == null) keyTxt[k] = new HashSet<int>(); keyTxt[k].Add(p.Txt[a]); }
                }
            p.Descriptive = new bool[nk];
            for (int k = 0; k < nk; k++) p.Descriptive[k] = keyTxt[k] != null && keyNiins[k] >= 20 && keyTxt[k].Count > 0.5 * keyNiins[k];
            cacheIx[pool] = cache.AddFirst(p); cachedAtoms += p.Atoms;
            while (cache.Count > 1 && (cache.Count > CacheSize || cachedAtoms > CacheAtoms))
            {
                var old = cache.Last; cache.RemoveLast(); cacheIx.Remove(old.Value.Pool); cachedAtoms -= old.Value.Atoms;
            }
            return p;
        }

