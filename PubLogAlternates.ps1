function Build-AltPartIndex {
    <#
    .SYNOPSIS
      Parses every PUB LOG characteristic reply and writes publog_alt.db.
      Skips the build when the index already matches publog.db's cut and
      parser version, unless -Force.
    #>
    [CmdletBinding()]
    param(
        [string]$PubLogDatabase = (Join-Path $PSScriptRoot 'publog.db'),
        [string]$AltDatabase,
        [switch]$Force,
        # Only report whether the index is current; never build.
        [switch]$WhatIfStale
    )
    $pl = Get-AltFullPath $PubLogDatabase
    if (-not (Test-Path -LiteralPath $pl)) { throw "PUB LOG database not found: $pl. Run Update-PubLogDatabase.ps1 first." }
    if (-not $AltDatabase) { $AltDatabase = Join-Path (Split-Path $pl -Parent) 'publog_alt.db' }
    $alt = Get-AltFullPath $AltDatabase
    if ((Test-Path -LiteralPath $alt) -and -not $Force) {
        $cur = $null; $pub = $null
        try {
            $a = New-Object AltParts.Db $alt
            try { $cur = $a.Rows('SELECT pub_date, parser_version FROM ac_build_log ORDER BY built_at DESC LIMIT 1') } finally { $a.Dispose() }
            $p = New-Object AltParts.Db $pl
            try { $pub = $p.Scalar("SELECT max(pub_date) FROM pl_load_log WHERE table_name IN ('V_CHARACTERISTICS','P_FLIS_NSN')") } finally { $p.Dispose() }
        } catch { Write-Warning "Could not read the existing index ($($_.Exception.Message)); rebuilding." }
        if ($cur -and $cur.Count -and "$($cur[0]['pub_date'])" -eq "$pub" -and "$($cur[0]['parser_version'])" -eq [AltParts.Builder]::ParserVersion) {
            Write-Host "  Alternate-part index is current (PUB LOG $pub). Use -Force to rebuild."
            return
        }
        if ($WhatIfStale) {
            $built = if ($cur -and $cur.Count) { "PUB LOG $($cur[0]['pub_date']), parser $($cur[0]['parser_version'])" } else { 'an unknown cut' }
            Write-Warning "The alternate-part index was built from $built, but publog.db is PUB LOG $pub (parser $([AltParts.Builder]::ParserVersion)). Results reflect the older data until you run Build-AltPartIndex -Force."
            return
        }
    }
    if ($WhatIfStale) { return }
    Write-Host "== Alternate-part index: $pl -> $alt ==" -ForegroundColor Cyan
    $log = [Action[string]] { param($m) Write-Host $m }
    $stats = [AltParts.Builder]::Build($pl, $alt, $log)
    Write-Host ("  Built in {0:N1} min: {1:N0} replies, {2:N0} atoms, {3:N0} NIINs, {4:N0} pools (PUB LOG {5})." -f ($stats['seconds'] / 60), $stats['replies'], $stats['atoms'], $stats['niins'], $stats['pools'], $stats['pub_date']) -ForegroundColor Green
    Write-AltPartQualitySummary -AltDatabase $alt
}

function Write-AltPartQualitySummary {
    # Short console digest of parse coverage; full detail is in ac_mrc / ac_pool_char.
    param([Parameter(Mandatory)][string]$AltDatabase, [int]$Top = 10)
    $a = New-Object AltParts.Db (Get-AltFullPath $AltDatabase)
    try {
        $t = $a.Rows('SELECT sum(replies) r, sum(numeric_replies) n, sum(text_replies) t, sum(empty_replies) e, sum(unparsed_numeric) u FROM ac_mrc')[0]
        Write-Host ("  Replies: {0:N0} numeric, {1:N0} text, {2:N0} empty. Text replies that still end in a number (unit not recognised): {3:N0}." -f $t['n'], $t['t'], $t['e'], $t['u'])
        $gaps = $a.Rows("SELECT mrc, statement, unparsed_numeric, text_replies, example_unparsed FROM ac_mrc WHERE unparsed_numeric > 0 ORDER BY unparsed_numeric DESC LIMIT $Top")
        if ($gaps.Count) {
            Write-Host "  Largest parse gaps (stored as text, compared only by exact wording):" -ForegroundColor Yellow
            foreach ($g in $gaps) { Write-Host ("    {0} {1,-40} {2,9:N0}  e.g. {3}" -f $g['mrc'], $g['statement'], $g['unparsed_numeric'], $g['example_unparsed']) }
        }
        $o = $a.Rows('SELECT count(*) c, sum(outliers) o FROM ac_pool_char WHERE outliers > 0')[0]
        Write-Host ("  Possible unit/decimal errors (value 10x+ from its pool median): {0:N0} values across {1:N0} pool characteristics (see ac_pool_char.outliers)." -f $o['o'], $o['c'])
    } finally { $a.Dispose() }
}
