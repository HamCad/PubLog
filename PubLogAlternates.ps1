    // ------------------------------------------------------------------
    // Server: a deliberately small HTTP/1.1 server on 127.0.0.1 only
    // (TcpListener: no admin rights, no URL reservation, no HTTP.sys).
    // ------------------------------------------------------------------
    public sealed class Server : IDisposable
    {
        TcpListener listener; Engine engine; string htmlPath; public int Port; public Action<string> Log;
        public string Url { get { return "http://127.0.0.1:" + Port + "/"; } }
        public Server(Engine e, string html, int port)
        {
            engine = e; htmlPath = html;
            listener = new TcpListener(IPAddress.Loopback, port);
            listener.Start();
            Port = ((IPEndPoint)listener.LocalEndpoint).Port;
        }
        public void Dispose()
        {
            foreach (var kv in open) { try { kv.Key.Close(); } catch { } }
            open.Clear();
            if (listener != null) { listener.Stop(); listener = null; }
        }

        // Browsers open speculative connections that may never carry a request,
        // so connections are collected and only those with data waiting are
        // served; idle ones are dropped after 30 s. Waits up to waitMs for one
        // request; returns false on timeout so the PowerShell loop around it
        // stays responsive to Ctrl+C.
        readonly List<KeyValuePair<TcpClient, DateTime>> open = new List<KeyValuePair<TcpClient, DateTime>>();
        public bool ServeOne(int waitMs)
        {
            var until = DateTime.UtcNow.AddMilliseconds(waitMs);
            while (true)
            {
                while (listener.Pending()) open.Add(new KeyValuePair<TcpClient, DateTime>(listener.AcceptTcpClient(), DateTime.UtcNow));
                for (int i = 0; i < open.Count; i++)
                {
                    TcpClient c = open[i].Key;
                    bool ready = false, dead = false;
                    try { ready = c.Available > 0; if (!ready) dead = c.Client.Poll(0, SelectMode.SelectRead); } catch { dead = true; }
                    if (ready) { open.RemoveAt(i); Serve(c); return true; }
                    if (dead || (DateTime.UtcNow - open[i].Value).TotalSeconds > 30) { try { c.Close(); } catch { } open.RemoveAt(i); i--; }
                }
                if (DateTime.UtcNow >= until) return false;
                System.Threading.Thread.Sleep(5);
            }
        }

        void Serve(TcpClient c)
        {
            using (c)
            {
                c.ReceiveTimeout = 15000; c.SendTimeout = 15000;
                var sw = System.Diagnostics.Stopwatch.StartNew();
                NetworkStream ns = c.GetStream();
                string method = "?", target = "?"; int status = 500;
                try
                {
                    byte[] head = ReadHead(ns);
                    string headText = Encoding.ASCII.GetString(head);
                    string[] lines = headText.Split(new[] { "\r\n" }, StringSplitOptions.None);
                    string[] rl = lines[0].Split(' ');
                    if (rl.Length < 3) { status = 400; Send(ns, 400, "application/json", Err("Bad request line.")); return; }
                    method = rl[0]; target = rl[1];
                    var headers = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                    for (int i = 1; i < lines.Length; i++) { int k = lines[i].IndexOf(':'); if (k > 0) headers[lines[i].Substring(0, k).Trim()] = lines[i].Substring(k + 1).Trim(); }
                    // DNS-rebinding guard: only answer requests addressed to this machine.
                    string host; headers.TryGetValue("Host", out host);
                    if (host != "127.0.0.1:" + Port && host != "localhost:" + Port) { status = 403; Send(ns, 403, "application/json", Err("Host not allowed.")); return; }
                    string body = "";
                    string cl;
                    if (headers.TryGetValue("Content-Length", out cl))
                    {
                        int n = int.Parse(cl, CultureInfo.InvariantCulture);
                        if (n > 8 * 1024 * 1024) { status = 413; Send(ns, 413, "application/json", Err("Body too large.")); return; }
                        byte[] b = new byte[n]; int got = 0;
                        while (got < n) { int r = ns.Read(b, got, n - got); if (r <= 0) break; got += r; }
                        body = Encoding.UTF8.GetString(b, 0, got);
                    }
                    string path = target, query = "";
                    int qm = target.IndexOf('?'); if (qm >= 0) { path = target.Substring(0, qm); query = target.Substring(qm + 1); }
                    var q = new Dictionary<string, string>();
                    foreach (string kv in query.Split(new[] { '&' }, StringSplitOptions.RemoveEmptyEntries))
                    {
                        int e = kv.IndexOf('=');
                        string k = Uri.UnescapeDataString((e < 0 ? kv : kv.Substring(0, e)).Replace('+', ' '));
                        string v = e < 0 ? "" : Uri.UnescapeDataString(kv.Substring(e + 1).Replace('+', ' '));
                        q[k] = v;
                    }
                    if (path == "/" || path == "/index.html")
                    {
                        status = 200; Send(ns, 200, "text/html; charset=utf-8", File.ReadAllBytes(htmlPath));
                    }
                    else if (path.StartsWith("/api/"))
                    {
                        string json = engine.Handle(method, path, q, body);
                        status = 200; Send(ns, 200, "application/json; charset=utf-8", Encoding.UTF8.GetBytes(json));
                    }
                    else { status = 404; Send(ns, 404, "application/json", Err("Not found: " + path)); }
                }
                catch (KeyNotFoundException e) { status = 404; TrySend(ns, 404, Err(e.Message)); }
                catch (ArgumentException e) { status = 400; TrySend(ns, 400, Err(e.Message)); }
                catch (Exception e) { status = 500; TrySend(ns, 500, Err(e.GetType().Name + ": " + e.Message)); if (Log != null) Log("  ERROR " + e); }
                finally
                {
                    if (Log != null) Log(string.Format(CultureInfo.InvariantCulture, "  {0} {1} {2} {3}ms", status, method, target.Length > 90 ? target.Substring(0, 90) + "..." : target, sw.ElapsedMilliseconds));
                }
            }
        }

        static byte[] ReadHead(NetworkStream ns)
        {
            var buf = new List<byte>(); int b; int match = 0;
            while ((b = ns.ReadByte()) >= 0)
            {
                buf.Add((byte)b);
                match = (b == '\r' && (match == 0 || match == 2)) || (b == '\n' && (match == 1 || match == 3)) ? match + 1 : (b == '\r' ? 1 : 0);
                if (match == 4) break;
                if (buf.Count > 65536) throw new ArgumentException("Header too large.");
            }
            return buf.ToArray();
        }
        static byte[] Err(string m) { return Encoding.UTF8.GetBytes(new JavaScriptSerializer().Serialize(new Dictionary<string, object> { { "error", m } })); }
        static void TrySend(NetworkStream ns, int code, byte[] body) { try { Send(ns, code, "application/json; charset=utf-8", body); } catch { } }
        static void Send(NetworkStream ns, int code, string type, byte[] body)
        {
            string reason = code == 200 ? "OK" : code == 400 ? "Bad Request" : code == 403 ? "Forbidden" : code == 404 ? "Not Found" : code == 413 ? "Payload Too Large" : "Internal Server Error";
            string h = "HTTP/1.1 " + code + " " + reason + "\r\nContent-Type: " + type + "\r\nContent-Length: " + body.Length +
                       "\r\nCache-Control: no-store\r\nX-Content-Type-Options: nosniff\r\nConnection: close\r\n\r\n";
            byte[] hb = Encoding.ASCII.GetBytes(h);
            ns.Write(hb, 0, hb.Length); ns.Write(body, 0, body.Length); ns.Flush();
        }
    }
}
