        }
        List<object> Outliers(PoolData p, string mrc, string qual, double med, double cut, int max)
        {
            var list = new List<object>();
            int key = p.FindKey(mrc, qual);
            if (key < 0 || double.IsNaN(med) || med <= 0) return list;
            for (int ix = 0; ix < p.Niins.Length && list.Count < max; ix++)
                for (int a = p.Start[ix]; a < p.End[ix]; a++)
                {
                    if (p.Key[a] != key || p.Kind[a] == 0) continue;
                    double v = (p.Lo[a] + p.Hi[a]) / 2;
                    if (v > 0 && Math.Abs(Math.Log10(v / med)) >= cut - 1e-9) { list.Add(new Dictionary<string, object> { { "niin", NiinText(p.Niins[ix]) }, { "value", Summary(p, new List<int> { a }) } }); break; }
                }
            return list;
        }
