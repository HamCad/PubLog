        public string Handle(string method, string path, Dictionary<string, string> q, string body)
        {
            object result;
            switch (path)
            {
                case "/api/status": result = Status(); break;
                case "/api/resolve": result = Resolve(Get(q, "q")); break;
                case "/api/item": result = Item(ParseNiin(Get(q, "niin"))); break;
                case "/api/pool": result = PoolProfile(ParsePools(Get(q, "pool")), Get(q, "seed")); break;
                case "/api/pools": result = FindPools(Get(q, "q")); break;
                case "/api/family": result = NameFamily(Get(q, "name"), Get(q, "nonApproved") == "1"); break;
                case "/api/ancestors": result = NameAncestors(Get(q, "name")); break;
                case "/api/search":
                    if (method != "POST") throw new ArgumentException("POST a JSON body to /api/search.");
                    result = Search((Dictionary<string, object>)js.DeserializeObject(body)); break;
                case "/api/compare": result = Compare(Get(q, "niins")); break;
                case "/api/quality": result = Quality(ParsePools(Get(q, "pool"))); break;
                default: throw new KeyNotFoundException("No such endpoint: " + path);
            }
            return js.Serialize(result);
        }
        static string Get(Dictionary<string, string> q, string k) { string v; return q != null && q.TryGetValue(k, out v) ? v : null; }
        public static long ParseNiin(string s)
        {
            string d = new string((s ?? "").Where(char.IsDigit).ToArray());
            if (d.Length == 13) d = d.Substring(4);
            long n;
            if (d.Length != 9 || !long.TryParse(d, out n)) throw new ArgumentException("Expected a 9-digit NIIN or 13-digit NSN, got '" + s + "'.");
            return n;
        }
        static List<long> ParsePools(string s)
        {
            var list = new List<long>();
            foreach (string p in (s ?? "").Split(new[] { ',' }, StringSplitOptions.RemoveEmptyEntries)) { long v; if (long.TryParse(p.Trim(), out v)) list.Add(v); }
            if (list.Count == 0) throw new ArgumentException("pool is required.");
            return list;
        }

