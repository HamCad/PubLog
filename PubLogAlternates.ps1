        // ---- pool profile ---------------------------------------------------------
        object PoolProfile(List<long> pools, string seed)
        {
            var info = new List<object>();
            foreach (long pool in pools) { var r = Db.Rows("SELECT * FROM ac_pool WHERE pool = ?", pool); if (r.Count > 0) info.Add(r[0]); }
            // Merge per-pool char stats across the selected pools.
            var chars = new Dictionary<string, Dictionary<string, object>>();
            long total = 0;
            foreach (long pool in pools)
            {
                object pn = Db.Scalar("SELECT niins FROM ac_pool WHERE pool = ?", pool); total += pn == null ? 0 : Convert.ToInt64(pn);
                foreach (var r in Db.Rows("SELECT * FROM ac_pool_char WHERE pool = ?", pool))
                {
                    string k = r["mrc"] + "\u0001" + r["qual"];
                    Dictionary<string, object> c;
                    if (!chars.TryGetValue(k, out c))
                    {
                        c = new Dictionary<string, object> { { "mrc", r["mrc"] }, { "qual", r["qual"] }, { "statement", Statement((string)r["mrc"]) },
                            { "niins", 0L }, { "n_num", 0L }, { "n_txt", 0L }, { "outliers", 0L }, { "units", r["units"] }, { "dims", r["dims"] },
                            { "distinct_txt", r["distinct_txt"] }, { "v_min", r["v_min"] }, { "v_med", r["v_med"] }, { "v_max", r["v_max"] }, { "v_p05", r["v_p05"] }, { "v_p95", r["v_p95"] },
                            { "outlier_example", r["outlier_example"] }, { "top_txt", TopTxt(r["top_txt"] as string) } };
                        chars[k] = c;
                    }
                    c["niins"] = (long)c["niins"] + Convert.ToInt64(r["niins"]);
                    c["n_num"] = (long)c["n_num"] + Convert.ToInt64(r["n_num"]);
                    c["n_txt"] = (long)c["n_txt"] + Convert.ToInt64(r["n_txt"]);
                    c["outliers"] = (long)c["outliers"] + Convert.ToInt64(r["outliers"] ?? 0L);
                }
            }
            foreach (var c in chars.Values)
            {
                c["coverage"] = total > 0 ? Math.Round((double)(long)c["niins"] / total, 4) : 0;
                c["numeric"] = (long)c["n_num"] > (long)c["n_txt"];
                string u = c["units"] as string;
                string unit = u == null ? null : u.Split(';')[0].Split(':')[0];
                if (unit == "(none)") unit = null;
                c["displayUnit"] = unit;
                c["mixedUnits"] = u != null && u.Contains(";");
                c["mixedKinds"] = (long)c["n_num"] > 0 && (long)c["n_txt"] > 0;
                if (unit != null)
                    foreach (string f in new[] { "v_min", "v_med", "v_max", "v_p05", "v_p95" })
                        if (c[f] != null) c[f + "Display"] = Num(Units.FromCanon(unit, Convert.ToDouble(c[f])));
            }
            var res = new Dictionary<string, object> { { "pools", info }, { "niins", total },
                { "chars", chars.Values.OrderByDescending(c => (long)c["niins"]).ToList() } };
            if (!string.IsNullOrEmpty(seed))
            {
                long sn = ParseNiin(seed);
                long sp = PoolOf(sn);
                if (sp != long.MinValue) { PoolData pd = LoadPool(sp); int ix; if (pd.NiinIx.TryGetValue(sn, out ix)) res["seedAtoms"] = AtomsOf(pd, ix); }
            }
            return res;
        }
        static List<object> TopTxt(string packed)
        {
            var list = new List<object>();
            if (string.IsNullOrEmpty(packed)) return list;
            foreach (string e in packed.Split('\u0001')) { string[] f = e.Split('\u0002'); if (f.Length == 2) list.Add(new Dictionary<string, object> { { "txt", f[0] }, { "n", int.Parse(f[1]) } }); }
            return list;
        }

        // ---- search --------------------------------------------------------------
        sealed class Constraint
        {
            public string Mrc, Qual, Mode, Test, Missing; public bool AnyQual;
            public HashSet<string> Values = new HashSet<string>();
            // Value families: "STEEL" stands for STEEL, STEEL COMP 302, STEEL CORROSION RESISTING, ...
            public HashSet<string> Families = new HashSet<string>();
            public double Lo = double.NaN, Hi = double.NaN;
        }

        static string S(Dictionary<string, object> d, string k) { object v; return d.TryGetValue(k, out v) && v != null ? v.ToString() : null; }
        static double D(Dictionary<string, object> d, string k)
        {
            object v; if (!d.TryGetValue(k, out v) || v == null) return double.NaN;
            double x; return double.TryParse(Convert.ToString(v, IC), NumberStyles.Float, IC, out x) ? x : double.NaN;
        }

        // MRCs that describe paperwork or usage rather than the item's form, fit
        // or function: shown and lockable, but never part of the similarity score.
        public static readonly HashSet<string> NonPhysical = new HashSet<string> { "AGAV", "AYDS", "AYDR", "AJJW", "AJJX", "AJJY", "AJJZ", "AJKE", "CXCY", "CRTL", "FEAT", "TEXT" };

        // Ids: every string id the constraint accepts (values and family members);
        // ValIds: the explicitly named values; Fams: one id set per family.
        sealed class Prepared { public bool[] KeyMatch; public HashSet<int> Ids = new HashSet<int>(), ValIds = new HashSet<int>(); public List<HashSet<int>> Fams = new List<HashSet<int>>(); public int Absent; }
        sealed class SeedKey { public string Mrc, Qual; public bool Text; public List<string> Txt = new List<string>(); public List<double> Mid = new List<double>(); }
        sealed class Cand { public PoolData P; public int Ix; public double Score; public int Matched, Compared, Unknown; }

        static Prepared Prepare(PoolData p, Constraint c)
        {
            var pr = new Prepared { KeyMatch = new bool[p.KeyMrc.Count] };
            for (int k = 0; k < pr.KeyMatch.Length; k++) pr.KeyMatch[k] = p.KeyMrc[k] == c.Mrc && (c.AnyQual || p.KeyQual[k] == c.Qual);
            foreach (string v in c.Values) { int i; if (p.StringIx.TryGetValue(v, out i)) pr.ValIds.Add(i); else pr.Absent++; }
            pr.Ids.UnionWith(pr.ValIds);
            foreach (string fam in c.Families)
            {
                var set = new HashSet<int>();
                for (int i = 0; i < p.Strings.Count; i++) if (InFamily(p.Strings[i], fam)) set.Add(i);
                pr.Fams.Add(set); pr.Ids.UnionWith(set);
            }
            return pr;
        }

        // A value belongs to a family when it is the family's wording or starts
        // with it followed by a word break: STEEL COMP 302 is in STEEL and in
        // STEEL COMP, but STEELITE is not in STEEL.
        public static bool InFamily(string s, string fam)
        {
            if (s == null || string.IsNullOrEmpty(fam) || !s.StartsWith(fam, StringComparison.Ordinal)) return false;
            return s.Length == fam.Length || s[fam.Length] == ' ' || s[fam.Length] == ',';
        }

        // The families a value can be grouped under: each leading run of words
        // (at most four) and the value itself. "STEEL COMP 302" -> STEEL, STEEL COMP, STEEL COMP 302.
        public static List<string> FamiliesOf(string s)
        {
            var list = new List<string>();
            if (string.IsNullOrEmpty(s)) return list;
            for (int i = 1; i < s.Length && list.Count < 4; i++)
                if ((s[i] == ' ' || s[i] == ',') && s[i - 1] != ' ' && s[i - 1] != ',') list.Add(s.Substring(0, i));
            list.Add(s);
            return list;
        }

        static bool Passes(PoolData p, int ix, Constraint c, Prepared pr, List<int> ids)
        {
            bool any = false, ok = false;
            ids.Clear();
            double L = double.IsNaN(c.Lo) ? double.NegativeInfinity : c.Lo, H = double.IsNaN(c.Hi) ? double.PositiveInfinity : c.Hi;
            for (int a = p.Start[ix]; a < p.End[ix]; a++)
            {
                if (!pr.KeyMatch[p.Key[a]]) continue;
                any = true;
                if (p.Kind[a] == 0) { ids.Add(p.Txt[a]); continue; }
                if (c.Mode != "range" || ok) continue;
                double lo = p.Lo[a], hi = p.Hi[a];
                double eps = 1e-9 * Math.Max(1, Math.Max(double.IsInfinity(L) ? 0 : Math.Abs(L), double.IsInfinity(H) ? 0 : Math.Abs(H)));
                if (c.Test == "overlap") ok = hi >= L - eps && lo <= H + eps;
                else if (c.Test == "covers") ok = lo <= L + eps && hi >= H - eps;
                else ok = lo >= L - eps && hi <= H + eps;
            }
            if (!any) return c.Mode == "absent" || c.Missing == "include";
            switch (c.Mode)
            {
                case "exists": return true;
                case "absent": return false;
                case "range": return ok;
                case "any": foreach (int i in ids) if (pr.Ids.Contains(i)) return true; return false;
                case "none": foreach (int i in ids) if (pr.Ids.Contains(i)) return false; return true;
                case "all": { if (pr.Absent > 0) return false; var h = new HashSet<int>(ids); return pr.ValIds.All(h.Contains) && pr.Fams.All(f => f.Overlaps(h)); }
                case "exact": { if (pr.Absent > 0) return false; var h = new HashSet<int>(ids); return pr.ValIds.All(h.Contains) && pr.Fams.All(f => f.Overlaps(h)) && h.All(pr.Ids.Contains); }
                default: throw new ArgumentException("Unknown criterion mode '" + c.Mode + "'.");
            }
        }

        static int BitIndex(long single) { int i = 0; while ((single & 1) == 0) { single >>= 1; i++; } return i; }

        static double NumSim(List<double> a, List<double> b)
        {
            double best = 0;
            foreach (double x in a)
                foreach (double y in b)
                {
                    double den = Math.Max(Math.Abs(x), Math.Abs(y));
                    double rel = den < 1e-12 ? 0 : Math.Abs(x - y) / den;
                    double s = rel <= 1e-6 ? 1 : rel <= 0.01 ? 0.9 : rel <= 0.05 ? 0.7 : rel <= 0.15 ? 0.4 : rel <= 0.3 ? 0.15 : 0;
                    if (s > best) best = s;
                }
            return best;
        }

        object Search(Dictionary<string, object> req)
        {
            var sw = System.Diagnostics.Stopwatch.StartNew();
            var poolsRaw = req.ContainsKey("pools") && req["pools"] != null ? (object[])req["pools"] : new object[0];
            var pools = poolsRaw.Select(x => Convert.ToInt64(x, IC)).Distinct().ToList();
            string seedS = S(req, "seed");
            long seed = string.IsNullOrEmpty(seedS) ? -1 : ParseNiin(seedS);
            if (pools.Count == 0 && seed >= 0) { long sp = PoolOf(seed); if (sp != long.MinValue) pools.Add(sp); }
            if (pools.Count == 0) throw new ArgumentException("Pick an item or an item-name pool first.");
            var data = pools.Select(LoadPool).ToList();

            PoolData seedPool = null; int seedIx = -1;
            if (seed >= 0) { long sp = PoolOf(seed); if (sp != long.MinValue) { seedPool = LoadPool(sp); if (!seedPool.NiinIx.TryGetValue(seed, out seedIx)) seedIx = -1; } }

            var cons = new List<Constraint>();
            if (req.ContainsKey("constraints") && req["constraints"] != null)
                foreach (object o in (object[])req["constraints"])
                {
                    var d = (Dictionary<string, object>)o;
                    var c = new Constraint { Mrc = S(d, "mrc"), Qual = S(d, "qual") ?? "", Mode = (S(d, "mode") ?? "any").ToLowerInvariant(), Test = (S(d, "test") ?? "within").ToLowerInvariant(),
                        Missing = (S(d, "missing") ?? "exclude").ToLowerInvariant(), AnyQual = Convert.ToBoolean(d.ContainsKey("anyQual") ? d["anyQual"] : false) };
                    if (c.Mode == "ignore") continue;
                    if (d.ContainsKey("values") && d["values"] != null) foreach (object v in (object[])d["values"]) c.Values.Add(ReplyParser.NormText(Convert.ToString(v, IC)));
                    if (d.ContainsKey("families") && d["families"] != null) foreach (object v in (object[])d["families"]) { string f = ReplyParser.NormText(Convert.ToString(v, IC)); if (f.Length > 0) c.Families.Add(f); }
                    double lo = D(d, "lo"), hi = D(d, "hi");
                    Unit u = S(d, "unit") == null ? null : Units.Find(S(d, "unit"));
                    c.Lo = u == null || double.IsNaN(lo) ? lo : u.ToCanon(lo);
                    c.Hi = u == null || double.IsNaN(hi) ? hi : u.ToCanon(hi);
                    if (!double.IsNaN(c.Lo) && !double.IsNaN(c.Hi) && c.Lo > c.Hi) { double t = c.Lo; c.Lo = c.Hi; c.Hi = t; }
                    cons.Add(c);
                }
            int nc = cons.Count;
            if (nc > 62) throw new ArgumentException("At most 62 criteria at once.");

            // The seed's physical characteristics, used for the similarity score.
            var seedKeys = new List<SeedKey>();
            if (seedPool != null && seedIx >= 0)
            {
                var byKey = new Dictionary<int, SeedKey>();
                for (int a = seedPool.Start[seedIx]; a < seedPool.End[seedIx]; a++)
                {
                    int k = seedPool.Key[a];
                    if (NonPhysical.Contains(seedPool.KeyMrc[k]) || seedPool.Descriptive[k]) continue;
                    SeedKey sk;
                    if (!byKey.TryGetValue(k, out sk)) { sk = new SeedKey { Mrc = seedPool.KeyMrc[k], Qual = seedPool.KeyQual[k], Text = seedPool.Kind[a] == 0 }; byKey[k] = sk; }
                    if (seedPool.Kind[a] == 0) { if (seedPool.Txt[a] >= 0) sk.Txt.Add(seedPool.Strings[seedPool.Txt[a]]); }
                    else sk.Mid.Add((seedPool.Lo[a] + seedPool.Hi[a]) / 2);
                }
                seedKeys = byKey.Values.ToList();
            }
            int K = seedKeys.Count;

            // Facets requested by the page.
            var fm = new List<string>(); var fq = new List<string>(); var fLimit = new List<int>();
            if (req.ContainsKey("facets") && req["facets"] != null)
                foreach (object o in (object[])req["facets"])
                {
                    var d = (Dictionary<string, object>)o; fm.Add(S(d, "mrc")); fq.Add(S(d, "qual") ?? "");
                    double lim = D(d, "limit"); fLimit.Add(double.IsNaN(lim) ? 60 : Math.Max(1, Math.Min(1000, (int)lim)));
                    if (fm.Count >= 80) break;
                }
            int F = fm.Count;
            // Family counts per facet: NIINs with any value in the family, each NIIN once.
            var fFam = new Dictionary<string, int>[F]; var fFamStamp = new Dictionary<string, int>[F];
            for (int f = 0; f < F; f++) { fFam[f] = new Dictionary<string, int>(); fFamStamp[f] = new Dictionary<string, int>(); }
            var fCons = new int[F]; var fBase = new int[F]; var fHave = new int[F]; var fUnit = new string[F];
            var fTxt = new Dictionary<string, int>[F]; var fVals = new List<double>[F];
            for (int f = 0; f < F; f++) { fCons[f] = cons.FindIndex(c => c.Mrc == fm[f] && (c.AnyQual || c.Qual == fq[f])); fTxt[f] = new Dictionary<string, int>(); fVals[f] = new List<double>(); }

            var rows = new List<Cand>();
            int poolNiins = 0; var fails = new int[nc]; var only = new int[nc];
            var ids = new List<int>();
            foreach (PoolData p in data)
            {
                var prep = cons.Select(c => Prepare(p, c)).ToArray();
                var keyToSeed = Enumerable.Repeat(-1, p.KeyMrc.Count).ToArray();
                for (int si = 0; si < K; si++) { int k = p.FindKey(seedKeys[si].Mrc, seedKeys[si].Qual); if (k >= 0) keyToSeed[k] = si; }
                var seedIds = new HashSet<int>[K];
                for (int si = 0; si < K; si++)
                    if (seedKeys[si].Text) { seedIds[si] = new HashSet<int>(); foreach (string t in seedKeys[si].Txt) { int i; seedIds[si].Add(p.StringIx.TryGetValue(t, out i) ? i : -1 - seedIds[si].Count); } }
                var keyToFacets = new List<int>[p.KeyMrc.Count];
                for (int f = 0; f < F; f++) { int k = p.FindKey(fm[f], fq[f]); if (k >= 0) { if (keyToFacets[k] == null) keyToFacets[k] = new List<int>(); keyToFacets[k].Add(f); } }
                var cTxt = new HashSet<int>[K]; var cMid = new List<double>[K];
                for (int si = 0; si < K; si++) { cTxt[si] = new HashSet<int>(); cMid[si] = new List<double>(); }
                var lastFacetIx = Enumerable.Repeat(-1, F).ToArray();
                var famsOfStr = new Dictionary<int, List<string>>();

                for (int ix = 0; ix < p.Niins.Length; ix++)
                {
                    poolNiins++;
                    long fail = 0;
                    for (int ci = 0; ci < nc; ci++) if (!Passes(p, ix, cons[ci], prep[ci], ids)) fail |= 1L << ci;
                    int onlyIdx = -1;
                    if (fail != 0)
                    {
                        for (int ci = 0; ci < nc; ci++) if ((fail & (1L << ci)) != 0) fails[ci]++;
                        if ((fail & (fail - 1)) == 0) { onlyIdx = BitIndex(fail); only[onlyIdx]++; }
                    }
                    // Facets count NIINs passing every criterion except the facet's own.
                    if (F > 0 && (fail == 0 || onlyIdx >= 0))
                    {
                        for (int f = 0; f < F; f++) if (fail == 0 || fCons[f] == onlyIdx) fBase[f]++;
                        for (int a = p.Start[ix]; a < p.End[ix]; a++)
                        {
                            var fl = keyToFacets[p.Key[a]]; if (fl == null) continue;
                            foreach (int f in fl)
                            {
                                if (!(fail == 0 || fCons[f] == onlyIdx)) continue;
                                if (lastFacetIx[f] != ix) { lastFacetIx[f] = ix; fHave[f]++; }
                                if (p.Kind[a] == 0)
                                {
                                    string t = p.Txt[a] >= 0 ? p.Strings[p.Txt[a]] : ""; int cnt; fTxt[f].TryGetValue(t, out cnt); fTxt[f][t] = cnt + 1;
                                    if (p.Txt[a] < 0 || p.Descriptive[p.Key[a]]) continue;
                                    List<string> fams;
                                    if (!famsOfStr.TryGetValue(p.Txt[a], out fams)) { fams = FamiliesOf(t); famsOfStr[p.Txt[a]] = fams; }
                                    foreach (string fam in fams)
                                    {
                                        int stamp; if (fFamStamp[f].TryGetValue(fam, out stamp) && stamp == poolNiins) continue;
                                        fFamStamp[f][fam] = poolNiins; fFam[f].TryGetValue(fam, out cnt); fFam[f][fam] = cnt + 1;
                                    }
                                }
                                else { fVals[f].Add((p.Lo[a] + p.Hi[a]) / 2); if (fUnit[f] == null && p.Txt[a] >= 0) fUnit[f] = p.Strings[p.Txt[a]]; }
                            }
                        }
                    }
                    if (fail != 0) continue;
                    if (seed >= 0 && p.Niins[ix] == seed) continue;
                    var cand = new Cand { P = p, Ix = ix };
                    if (K > 0)
                    {
                        for (int si = 0; si < K; si++) { cTxt[si].Clear(); cMid[si].Clear(); }
                        for (int a = p.Start[ix]; a < p.End[ix]; a++)
                        {
                            int si = keyToSeed[p.Key[a]]; if (si < 0) continue;
                            if (p.Kind[a] == 0) cTxt[si].Add(p.Txt[a]); else cMid[si].Add((p.Lo[a] + p.Hi[a]) / 2);
                        }
                        double sum = 0;
                        for (int si = 0; si < K; si++)
                        {
                            if (cTxt[si].Count == 0 && cMid[si].Count == 0) { cand.Unknown++; continue; }
                            double s;
                            if (seedKeys[si].Text)
                            {
                                if (cTxt[si].Count == 0) s = 0;
                                else { int inter = cTxt[si].Count(seedIds[si].Contains); s = (double)inter / (seedIds[si].Count + cTxt[si].Count - inter); }
                            }
                            else s = cMid[si].Count == 0 ? 0 : NumSim(seedKeys[si].Mid, cMid[si]);
                            cand.Compared++; sum += s; if (s >= 0.999) cand.Matched++;
                        }
                        cand.Score = sum / K;
                    }
                    rows.Add(cand);
                }
            }

            string sort = S(req, "sort") ?? "score";
            IEnumerable<Cand> ordered = sort == "niin" || K == 0
                ? rows.OrderBy(r => r.P.Niins[r.Ix])
                : rows.OrderByDescending(r => r.Score).ThenByDescending(r => r.Matched).ThenBy(r => r.P.Niins[r.Ix]);
            int limit = Math.Max(1, Math.Min(5000, (int)(D(req, "limit") > 0 ? D(req, "limit") : 100)));
            int offset = Math.Max(0, (int)(double.IsNaN(D(req, "offset")) ? 0 : D(req, "offset")));
            var page = ordered.Skip(offset).Take(limit).ToList();
            bool enrich = !(req.ContainsKey("enrich") && Equals(req["enrich"], false));
            var seedRel = seed >= 0 && enrich ? SeedRelationSet(NiinText(seed)) : new Dictionary<string, List<string>>();
            var outRows = new List<object>();
            foreach (var r in page)
            {
                var p = r.P; string ns = NiinText(p.Niins[r.Ix]);
                var d = new Dictionary<string, object> { { "niin", ns }, { "pool", p.Pool }, { "score", Math.Round(r.Score, 4) }, { "matched", r.Matched }, { "compared", r.Compared }, { "unknown", r.Unknown }, { "diffs", Diffs(seedKeys, p, r.Ix) } };
                if (enrich) Enrich(d, ns);
                List<string> tags; if (seedRel.TryGetValue(ns, out tags)) d["relations"] = tags;
                outRows.Add(d);
            }
            var facets = new List<object>();
            for (int f = 0; f < F; f++)
            {
                var fo = new Dictionary<string, object> { { "mrc", fm[f] }, { "qual", fq[f] }, { "base", fBase[f] }, { "have", fHave[f] }, { "missing", fBase[f] - fHave[f] }, { "distinct", fTxt[f].Count } };
                fo["values"] = fTxt[f].OrderByDescending(x => x.Value).ThenBy(x => x.Key).Take(fLimit[f]).Select(x => (object)new Dictionary<string, object> { { "txt", x.Key }, { "n", x.Value } }).ToList();
                fo["families"] = FacetFamilies(fTxt[f].Keys, fFam[f]);
                if (fVals[f].Count > 0) fo["hist"] = Histogram(fVals[f], fUnit[f]);
                facets.Add(fo);
            }
            var counts = new List<object>();
            for (int ci = 0; ci < nc; ci++) counts.Add(new Dictionary<string, object> { { "index", ci }, { "fails", fails[ci] }, { "onlyBlocker", only[ci] } });
            return new Dictionary<string, object> {
                { "total", rows.Count }, { "poolNiins", poolNiins }, { "scoredOn", K }, { "rows", outRows }, { "facets", facets },
                { "constraintCounts", counts }, { "ms", sw.ElapsedMilliseconds } };
        }

        // Families worth offering for one facet: a leading run of words shared by
        // two or more distinct values. A family with exactly the same values as a
        // longer one (COPPER when every COPPER value is COPPER ALLOY ...) is
        // dropped in favour of the longer, more telling wording.
        static List<object> FacetFamilies(IEnumerable<string> values, Dictionary<string, int> niinCounts)
        {
            var members = new Dictionary<string, int>();
            foreach (string v in values) foreach (string fam in FamiliesOf(v)) { int m; members.TryGetValue(fam, out m); members[fam] = m + 1; }
            var keep = members.Where(kv => kv.Value >= 2).Select(kv => kv.Key).ToList();
            var list = new List<object>();
            foreach (string fam in keep)
            {
                bool same = keep.Any(o => o.Length > fam.Length && InFamily(o, fam) && members[o] == members[fam]);
                if (same) continue;
                int n; niinCounts.TryGetValue(fam, out n);
                list.Add(new Dictionary<string, object> { { "txt", fam }, { "n", n }, { "members", members[fam] } });
            }
            return list.OrderByDescending(x => (int)((Dictionary<string, object>)x)["n"]).Take(200).ToList();
        }

        // The seed characteristics a candidate does not match exactly (for the page only).
        List<object> Diffs(List<SeedKey> seedKeys, PoolData p, int ix)
        {
            var list = new List<object>();
            foreach (var sk in seedKeys)
            {
                int key = p.FindKey(sk.Mrc, sk.Qual);
                var atoms = new List<int>();
                if (key >= 0) for (int a = p.Start[ix]; a < p.End[ix]; a++) if (p.Key[a] == key) atoms.Add(a);
                if (atoms.Count == 0) continue;
                double s;
                if (sk.Text)
                {
                    var c = new HashSet<string>(atoms.Where(a => p.Kind[a] == 0 && p.Txt[a] >= 0).Select(a => p.Strings[p.Txt[a]]));
                    var sset = new HashSet<string>(sk.Txt);
                    int inter = c.Count(sset.Contains); int uni = sset.Count + c.Count - inter;
                    s = uni == 0 ? 1 : (double)inter / uni;
                }
                else s = NumSim(sk.Mid, atoms.Where(a => p.Kind[a] != 0).Select(a => (p.Lo[a] + p.Hi[a]) / 2).ToList());
                if (s >= 0.999) continue;
                list.Add(new Dictionary<string, object> { { "mrc", sk.Mrc }, { "qual", sk.Qual }, { "statement", Statement(sk.Mrc) }, { "sim", Math.Round(s, 2) }, { "value", Summary(p, atoms) } });
                if (list.Count >= 8) break;
            }
            return list;
        }

        static string Summary(PoolData p, List<int> atoms)
        {
            var parts = new List<string>();
            foreach (int a in atoms)
            {
                if (p.Kind[a] == 0) { parts.Add(p.Txt[a] >= 0 ? p.Strings[p.Txt[a]] : ""); continue; }
                string u = p.Txt[a] >= 0 ? p.Strings[p.Txt[a]] : null;
                double lo = u == null ? p.Lo[a] : Units.FromCanon(u, p.Lo[a]), hi = u == null ? p.Hi[a] : Units.FromCanon(u, p.Hi[a]);
                string v = Math.Abs(lo - hi) < 1e-12 ? lo.ToString("G6", IC) : lo.ToString("G6", IC) + " to " + hi.ToString("G6", IC);
                string kind = PoolData.KindNames[p.Kind[a]];
                parts.Add((kind == "MIN" ? "min " : kind == "MAX" ? "max " : "") + v + (u != null ? " " + u.ToLowerInvariant() : ""));
            }
            return string.Join("; ", parts);
        }

        void Enrich(Dictionary<string, object> d, string ns)
        {
            var n = Db.Rows("SELECT fsc, item_name FROM pl.pl_p_flis_nsn WHERE niin = ? LIMIT 1", ns);
            if (n.Count > 0) { d["item_name"] = n[0]["item_name"]; d["nsn"] = (n[0]["fsc"] ?? "") + ns; d["fsc"] = n[0]["fsc"]; }
            var m = Db.Rows("SELECT aac, unit_price, ui, sos FROM pl.pl_v_flis_management WHERE niin = ?", ns);
            d["aac"] = string.Join(",", m.Select(x => x["aac"] as string).Where(x => !string.IsNullOrEmpty(x)).Distinct());
            var price = m.Select(x => x["unit_price"] as string).FirstOrDefault(x => !string.IsNullOrEmpty(x));
            d["unit_price"] = price; d["ui"] = m.Select(x => x["ui"] as string).FirstOrDefault(x => !string.IsNullOrEmpty(x));
            var aacs = ((string)d["aac"]).Split(',').Where(x => x.Length > 0).ToList();
            d["procurable"] = aacs.Count == 0 ? null : (object)!aacs.All(x => x == "V" || x == "T" || x == "Y" || x == "X" || x == "N");
