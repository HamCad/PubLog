        sealed class Acc
        {
            public long Niins, Num, Txt, LastNiin = -1;
            public Dictionary<string, int> TxtCount = new Dictionary<string, int>();
            public Dictionary<string, int> Dims = new Dictionary<string, int>();
            public Dictionary<string, int> UnitWords = new Dictionary<string, int>();
            public List<double> Vals = new List<double>();
            public List<long> ValNiin = new List<long>();
        }

        static void Flush(Db.Stmt ins, long pool, Dictionary<string, Acc> acc, Dictionary<long, long> poolNiins)
        {
            if (pool == long.MinValue) return;
            long total; poolNiins.TryGetValue(pool, out total);
            foreach (var kv in acc)
            {
                string[] k = kv.Key.Split('\u0001');
                Acc a = kv.Value;
                object vmin = null, p05 = null, med = null, p95 = null, vmax = null; int outliers = 0; string oex = null; double cut = double.NaN;
                if (a.Vals.Count > 0)
                {
                    var idx = Enumerable.Range(0, a.Vals.Count).OrderBy(i => a.Vals[i]).ToArray();
                    Func<double, double> q = p => a.Vals[idx[(int)Math.Round(p * (idx.Length - 1))]];
                    vmin = q(0); p05 = q(0.05); med = q(0.5); p95 = q(0.95); vmax = q(1);
                    // Possible unit / decimal-point errors: far from the pool median in
                    // log space -- at least 10x, and at least 5 median absolute
                    // deviations, so naturally wide groups (cable lengths) are not flagged.
                    double m = (double)med;
                    var logs = a.Vals.Where(v => v > 0).Select(v => Math.Log10(v)).ToList();
                    if (logs.Count >= 8 && m > 0)
                    {
                        logs.Sort();
                        double lm = logs[logs.Count / 2];
                        var dev = logs.Select(x => Math.Abs(x - lm)).OrderBy(x => x).ToList();
                        cut = Math.Max(1.0, 5 * dev[dev.Count / 2]);
                        double worst = 0;
                        foreach (int i in idx)
                        {
                            double v = a.Vals[i];
                            if (v <= 0) continue;
                            double dl = Math.Abs(Math.Log10(v) - lm);
                            if (dl >= cut) { outliers++; if (dl > worst) { worst = dl; oex = a.ValNiin[i].ToString("000000000") + "=" + v.ToString("G6", CultureInfo.InvariantCulture); } }
                        }
                    }
                }
                string top = string.Join("\u0001", a.TxtCount.OrderByDescending(x => x.Value).Take(12).Select(x => x.Key + "\u0002" + x.Value));
                ins.Reset();
                ins.Bind(pool, k[0], k[1], a.Niins, total > 0 ? (object)Math.Round((double)a.Niins / total, 4) : null, a.Num, a.Txt,
                    a.Dims.Count == 0 ? null : string.Join(";", a.Dims.OrderByDescending(x => x.Value).Select(x => (x.Key.Length == 0 ? "(implied)" : x.Key) + ":" + x.Value)),
                    a.UnitWords.Count == 0 ? null : string.Join(";", a.UnitWords.OrderByDescending(x => x.Value).Select(x => (x.Key.Length == 0 ? "(none)" : x.Key) + ":" + x.Value)),
                    a.TxtCount.Count, top.Length == 0 ? null : top, vmin, p05, med, p95, vmax, outliers, oex, double.IsNaN(cut) ? null : (object)cut);
                ins.Step();
            }
        }
